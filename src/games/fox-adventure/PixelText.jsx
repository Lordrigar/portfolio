const glyphs = {
  C: ['01111', '10000', '10000', '10000', '10000', '10000', '01111'],
  o: ['00000', '00000', '01110', '10001', '10001', '10001', '01110'],
  z: ['00000', '00000', '11111', '00010', '00100', '01000', '11111'],
  a: ['00000', '00000', '01110', '00001', '01111', '10001', '01111'],
  p: ['00000', '11110', '10001', '10001', '11110', '10000', '10000'],
  r: ['00000', '00000', '10110', '11001', '10000', '10000', '10000'],
  e: ['00000', '00000', '01110', '10001', '11111', '10000', '01111'],
  g: ['00000', '01111', '10001', '01111', '00001', '10001', '01110'],
  y: ['00000', '10001', '10001', '01111', '00001', '00010', '11100'],
  w: ['00000', '00000', '10001', '10001', '10101', '10101', '01010'],
};

export default function PixelText({ text }) {
  const letters = Array.from(text);
  return <svg className="defeat-title" viewBox={`0 0 ${letters.length * 6 - 1} 7`}
    role="img" aria-label={text} shapeRendering="crispEdges" fill="currentColor">
    {letters.flatMap((letter, index) => (glyphs[letter] ?? []).flatMap((row, y) =>
      Array.from(row).map((bit, x) => bit === '1'
        ? <rect key={`${index}-${x}-${y}`} x={index * 6 + x} y={y} width="1" height="1" />
        : null),
    ))}
  </svg>;
}
